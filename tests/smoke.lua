-- Run from the repository root:
-- lua5.4 tests/smoke.lua target/release/libwordninja_rs_lua.so
local open_module = assert(package.loadlib(assert(arg[1], "expected module path"), "luaopen_wordninja"))
local wordninja = open_module()

assert(wordninja.split("iloverust") == "i love rust")
local preset = wordninja.split("useserde")
local preset_the = wordninja.word_cost("the")
local model = wordninja.load_rime_dir("tests/fixtures/rime")
assert(model.files == 2 and model.entries == 4)
assert(model.count == 3 and model.added == 2 and model.preset_duplicates == 1)
assert(model.duplicates == 5 and model.skipped == 0)
assert(model.has_word("SERDE") and not model.has_word("ignoredheaderword"))
assert(not model.has_word("999999"))
assert(model.word_cost("serde") == 6)
assert(model.word_cost("the") == preset_the)
assert(model.split("useserde") == "use serde")
assert(model.split("usevecdeque") == "use vecdeque")
assert(model.split("useVecDeque") == "use VecDeque")
assert(wordninja.split("useserde") == preset)
assert(wordninja.word_cost("serde") == nil)
assert(not pcall(wordninja.load_rime_dir, "tests/fixtures/rime/missing"))

local path = os.tmpname()
local function write(contents)
    local file = assert(io.open(path, "wb"))
    assert(file:write(contents))
    assert(file:close())
end
local ok, err = pcall(function()
    write("\239\187\191# comment\r\nSerde\r\nserde 5\r\nVecDeque\r\nbad-word\r\n")
    local custom = wordninja.load_words(path)
    assert(custom.count == 2 and custom.skipped == 1 and custom.skipped_lines[1] == 5)
    assert(custom.default_cost == 6)
    assert(custom.split("useserde") == "use serde")
    assert(custom.split("usevecdeque") == "use vecdeque")
    assert(not pcall(wordninja.load_words, path, 0))
    assert(not pcall(wordninja.load_words, path, math.huge))
    assert(not pcall(wordninja.load_words, path, 0/0))

    write("# empty vocabulary\n")
    local empty = wordninja.load_words(path)
    assert(empty.count == 0 and empty.split("useserde") == preset)
    assert(custom.split("useserde") == "use serde")
    assert(model.split("useserde") == "use serde")
end)
os.remove(path)
assert(ok, err)
assert(not pcall(wordninja.load_words, path))
assert(wordninja.split("useserde") == preset)
print("wordninja Lua smoke tests passed")
